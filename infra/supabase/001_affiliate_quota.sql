-- Afiliados Creator: central quota ledger for Supabase Postgres.
-- Run ONLY through the Supabase SQL editor as the project database owner.
-- Do not expose affiliate_private schema via the REST exposed schema list.
-- All RPC calls below authenticate with Supabase user JWT; no service-role key
-- is required in the browser, renderer or public app.
BEGIN;

CREATE SCHEMA IF NOT EXISTS affiliate_private;
REVOKE ALL ON SCHEMA affiliate_private FROM PUBLIC, anon, authenticated;

CREATE TABLE IF NOT EXISTS affiliate_private.subscriptions (
  user_id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  plan text NOT NULL DEFAULT 'gratis'
    CHECK (plan IN ('gratis', 'pro', 'premium', 'creator')),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS affiliate_private.renders (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  plan_at_reservation text NOT NULL
    CHECK (plan_at_reservation IN ('gratis','pro','premium','creator')),
  status text NOT NULL CHECK (status IN ('reserved','completed')),
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  completed_at timestamptz
);
CREATE INDEX IF NOT EXISTS idx_affiliate_render_owner_status
  ON affiliate_private.renders(user_id,status,completed_at,created_at);

CREATE TABLE IF NOT EXISTS affiliate_private.free_attempts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  started_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX IF NOT EXISTS idx_affiliate_free_attempt_user_time
  ON affiliate_private.free_attempts(user_id,started_at);
CREATE INDEX IF NOT EXISTS idx_affiliate_free_attempt_global_time
  ON affiliate_private.free_attempts(started_at);

REVOKE ALL ON ALL TABLES IN SCHEMA affiliate_private FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA affiliate_private FROM PUBLIC, anon, authenticated;

-- The database function, not the HTTP client, decides the plan and quota.
-- One advisory lock protects the beta pool and avoids double reservations.
CREATE OR REPLACE FUNCTION public.affiliate_reserve_videos(p_count integer DEFAULT 1)
RETURNS uuid[]
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
DECLARE
  v_user uuid := auth.uid();
  v_plan text;
  v_limit integer;
  v_per_ad integer;
  v_now timestamptz;
  v_count integer;
  v_ids uuid[] := ARRAY[]::uuid[];
  v_new uuid;
  v_i integer;
BEGIN
  IF v_user IS NULL OR NOT EXISTS (
    SELECT 1 FROM auth.users u WHERE u.id = v_user AND u.email_confirmed_at IS NOT NULL
  ) THEN
    RAISE EXCEPTION 'Confirmacao de e-mail obrigatoria' USING ERRCODE = '42501';
  END IF;

  PERFORM pg_catalog.pg_advisory_xact_lock(819320123888::bigint);
  v_now := clock_timestamp();
  DELETE FROM affiliate_private.renders r
    WHERE r.status='reserved' AND r.created_at <= v_now - INTERVAL '6 hours';
  DELETE FROM affiliate_private.free_attempts a
    WHERE a.started_at <= v_now - INTERVAL '24 hours';

  SELECT s.plan INTO v_plan FROM affiliate_private.subscriptions s
    WHERE s.user_id = v_user;
  v_plan := COALESCE(v_plan, 'gratis');
  v_limit := CASE v_plan WHEN 'gratis' THEN 1 WHEN 'pro' THEN 3
                        WHEN 'premium' THEN 5 WHEN 'creator' THEN 10 ELSE 0 END;
  v_per_ad := CASE v_plan WHEN 'creator' THEN 3 ELSE 1 END;

  IF p_count IS NULL OR p_count < 1 OR p_count > v_per_ad OR v_limit = 0 THEN
    RAISE EXCEPTION 'Quantidade de videos nao permitida' USING ERRCODE='22023';
  END IF;

  IF v_plan = 'gratis' THEN
    IF EXISTS (
      SELECT 1 FROM affiliate_private.renders r
      WHERE r.user_id=v_user AND r.status='reserved'
    ) THEN
      RAISE EXCEPTION 'Geracao gratuita em andamento' USING ERRCODE='P0001';
    END IF;
    IF EXISTS (
      SELECT 1 FROM affiliate_private.renders r
      WHERE r.user_id=v_user AND r.status='completed'
        AND r.completed_at > v_now - INTERVAL '24 hours'
    ) THEN
      RAISE EXCEPTION 'Aguarde 24 horas apos o ultimo video' USING ERRCODE='P0001';
    END IF;
    IF (SELECT count(*) FROM affiliate_private.free_attempts a
        WHERE a.user_id=v_user AND a.started_at > v_now - INTERVAL '1 hour') >= 5
       OR (SELECT count(*) FROM affiliate_private.free_attempts a
        WHERE a.started_at > v_now - INTERVAL '1 hour') >= 12
       OR (SELECT count(*) FROM affiliate_private.free_attempts a
        WHERE a.started_at > v_now - INTERVAL '24 hours') >= 40
    THEN
      RAISE EXCEPTION 'Capacidade gratuita temporariamente esgotada' USING ERRCODE='P0001';
    END IF;
    INSERT INTO affiliate_private.free_attempts(user_id,started_at)
      VALUES(v_user,v_now);
  ELSE
    SELECT count(*) INTO v_count FROM affiliate_private.renders r
      WHERE r.user_id=v_user
        AND (r.created_at AT TIME ZONE 'America/Sao_Paulo')::date =
            (v_now AT TIME ZONE 'America/Sao_Paulo')::date;
    IF v_count + p_count > v_limit THEN
      RAISE EXCEPTION 'Cota diaria atingida' USING ERRCODE='P0001';
    END IF;
  END IF;

  FOR v_i IN 1..p_count LOOP
    INSERT INTO affiliate_private.renders(user_id,plan_at_reservation,status,created_at)
      VALUES(v_user,v_plan,'reserved',v_now) RETURNING id INTO v_new;
    v_ids := array_append(v_ids,v_new);
  END LOOP;
  RETURN v_ids;
END
$$;

CREATE OR REPLACE FUNCTION public.affiliate_complete_videos(p_ids uuid[])
RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
DECLARE
  v_user uuid := auth.uid();
  v_count integer;
BEGIN
  IF v_user IS NULL THEN
    RAISE EXCEPTION 'Autenticacao obrigatoria' USING ERRCODE='42501';
  END IF;
  IF p_ids IS NULL OR array_length(p_ids,1) IS NULL
     OR array_length(p_ids,1) > 3 THEN
    RAISE EXCEPTION 'Reservas invalidas' USING ERRCODE='22023';
  END IF;
  PERFORM pg_catalog.pg_advisory_xact_lock(819320123888::bigint);
  SELECT count(*) INTO v_count FROM affiliate_private.renders r
    WHERE r.id = ANY(p_ids) AND r.user_id=v_user AND r.status='reserved'
      AND r.created_at > clock_timestamp() - INTERVAL '6 hours';
  IF v_count <> array_length(p_ids,1) THEN
    RAISE EXCEPTION 'Reserva invalida, duplicada ou expirada' USING ERRCODE='P0001';
  END IF;
  UPDATE affiliate_private.renders r SET
    status='completed', completed_at=clock_timestamp()
    WHERE r.id=ANY(p_ids) AND r.user_id=v_user AND r.status='reserved';
END
$$;

CREATE OR REPLACE FUNCTION public.affiliate_release_videos(p_ids uuid[])
RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
DECLARE
  v_user uuid := auth.uid();
  v_count integer;
BEGIN
  IF v_user IS NULL THEN
    RAISE EXCEPTION 'Autenticacao obrigatoria' USING ERRCODE='42501';
  END IF;
  IF p_ids IS NULL OR array_length(p_ids,1) IS NULL
     OR array_length(p_ids,1) > 3 THEN
    RAISE EXCEPTION 'Reservas invalidas' USING ERRCODE='22023';
  END IF;
  PERFORM pg_catalog.pg_advisory_xact_lock(819320123888::bigint);
  SELECT count(*) INTO v_count FROM affiliate_private.renders r
    WHERE r.id=ANY(p_ids) AND r.user_id=v_user AND r.status='reserved';
  IF v_count <> array_length(p_ids,1) THEN
    RAISE EXCEPTION 'Reserva invalida ou duplicada' USING ERRCODE='P0001';
  END IF;
  DELETE FROM affiliate_private.renders r
    WHERE r.id=ANY(p_ids) AND r.user_id=v_user AND r.status='reserved';
END
$$;

CREATE OR REPLACE FUNCTION public.affiliate_free_status()
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
DECLARE
  v_user uuid := auth.uid();
  v_now timestamptz;
  v_completed timestamptz;
  v_in_progress boolean;
  v_user_attempts bigint;
  v_user_first timestamptz;
  v_hour_attempts bigint;
  v_hour_first timestamptz;
  v_day_attempts bigint;
  v_day_first timestamptz;
  v_cooldown integer := 0;
  v_retry integer := 0;
  v_capacity integer := 0;
BEGIN
  IF v_user IS NULL OR NOT EXISTS (
    SELECT 1 FROM auth.users u WHERE u.id=v_user AND u.email_confirmed_at IS NOT NULL
  ) THEN
    RAISE EXCEPTION 'Confirmacao de e-mail obrigatoria' USING ERRCODE='42501';
  END IF;

  PERFORM pg_catalog.pg_advisory_xact_lock(819320123888::bigint);
  v_now := clock_timestamp();
  DELETE FROM affiliate_private.renders r
    WHERE r.status='reserved' AND r.created_at <= v_now - INTERVAL '6 hours';
  DELETE FROM affiliate_private.free_attempts a
    WHERE a.started_at <= v_now - INTERVAL '24 hours';

  SELECT MAX(r.completed_at) INTO v_completed
    FROM affiliate_private.renders r
    WHERE r.user_id=v_user AND r.status='completed';
  SELECT EXISTS(
    SELECT 1 FROM affiliate_private.renders r
    WHERE r.user_id=v_user AND r.status='reserved'
  ) INTO v_in_progress;
  IF v_completed IS NOT NULL THEN
    v_cooldown := GREATEST(0,
      CEIL(EXTRACT(EPOCH FROM (v_completed + INTERVAL '24 hours' - v_now)))::integer);
  END IF;

  SELECT count(*), min(a.started_at) INTO v_user_attempts,v_user_first
    FROM affiliate_private.free_attempts a
    WHERE a.user_id=v_user AND a.started_at > v_now - INTERVAL '1 hour';
  SELECT count(*), min(a.started_at) INTO v_hour_attempts,v_hour_first
    FROM affiliate_private.free_attempts a
    WHERE a.started_at > v_now - INTERVAL '1 hour';
  SELECT count(*), min(a.started_at) INTO v_day_attempts,v_day_first
    FROM affiliate_private.free_attempts a
    WHERE a.started_at > v_now - INTERVAL '24 hours';

  IF v_user_attempts >= 5 THEN
    v_retry := GREATEST(0, CEIL(EXTRACT(EPOCH FROM
      (v_user_first + INTERVAL '1 hour' - v_now)))::integer);
  END IF;
  IF v_hour_attempts >= 12 THEN
    v_capacity := GREATEST(v_capacity, CEIL(EXTRACT(EPOCH FROM
      (v_hour_first + INTERVAL '1 hour' - v_now)))::integer);
  END IF;
  IF v_day_attempts >= 40 THEN
    v_capacity := GREATEST(v_capacity, CEIL(EXTRACT(EPOCH FROM
      (v_day_first + INTERVAL '24 hours' - v_now)))::integer);
  END IF;
  RETURN jsonb_build_object(
    'remaining_seconds', v_cooldown,
    'in_progress', v_in_progress,
    'attempt_retry_seconds', v_retry,
    'capacity_retry_seconds', v_capacity
  );
END
$$;

-- Read-only entitlement, sourced from protected billing state.
-- Never accept "plan" or "owner_id" from a request or JWT user_metadata.
CREATE OR REPLACE FUNCTION public.affiliate_my_plan()
RETURNS text
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
DECLARE
  v_user uuid := auth.uid();
  v_plan text;
BEGIN
  IF v_user IS NULL OR NOT EXISTS (
    SELECT 1 FROM auth.users u
    WHERE u.id = v_user AND u.email_confirmed_at IS NOT NULL
  ) THEN
    RAISE EXCEPTION 'Confirmacao de e-mail obrigatoria' USING ERRCODE='42501';
  END IF;
  SELECT s.plan INTO v_plan FROM affiliate_private.subscriptions s
    WHERE s.user_id = v_user;
  RETURN COALESCE(v_plan, 'gratis');
END
$$;

